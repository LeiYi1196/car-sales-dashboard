"""Natural-language query layer for the car-sales dashboard.

Architecture
------------
The user asks a question in plain English or Chinese.
Claude receives a compact data summary (date range, countries, total rows) as
context, then decides which tools to call to answer the question.
Each tool wraps existing analyzer.py functions — no raw SQL is ever passed to
or generated by the LLM.

Claude Sonnet 4.6 is used by default; override with CHAT_MODEL env var.
Requires ANTHROPIC_API_KEY in the environment (or .env file).

Public API
----------
    answer(question: str, session: Session) -> str
"""

