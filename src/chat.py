# ── 工具执行层（真实 Python 计算，绝不向 LLM 暴露原始 SQL）──────────────

def _run_tool(name: str, inputs: dict, df: pd.DataFrame) -> Any:
    """把 LLM 的工具调用路由到 analyzer 函数，返回可序列化的 dict/list。"""

    def _ts(s: str | None) -> pd.Timestamp | None:
        return pd.Timestamp(s) if s else None

    if name == "get_global_summary":
        g = summarize_all(
            df,
            start=_ts(inputs.get("start_date")),
            end=_ts(inputs.get("end_date")),
        )
        rows = g.by_country[["country", "display_name", "sales", "quantity", "orders"]].copy()
        rows["sales"] = rows["sales"].round(0).astype(int)
        return {
            "total_sales": round(g.total_sales, 0),
            "total_quantity": g.total_quantity,
            "order_count": g.order_count,
            "country_count": g.country_count,
            "date_range": [str(g.date_range[0])[:10], str(g.date_range[1])[:10]],
            "by_country": rows.to_dict(orient="records"),
        }

    if name == "get_country_detail":
        country = inputs["country"]
        gran = inputs.get("granularity", "M")
        # 允许大小写不敏感匹配
        country_map = {c.lower(): c for c in df["country"].unique()}
        country = country_map.get(country.lower(), country)
        s = summarize_country(df, country, granularity=gran)
        trend = s.trend[["period_label", "sales", "quantity", "pop_pct", "yoy_pct"]].copy()
        trend["sales"] = trend["sales"].round(0).astype(int)
        trend["pop_pct"] = trend["pop_pct"].round(1)
        trend["yoy_pct"] = trend["yoy_pct"].round(1)
        return {
            "country": s.country,
            "total_sales": round(s.total_sales, 0),
            "total_quantity": s.total_quantity,
            "date_range": [str(s.date_range[0])[:10] if s.date_range[0] else None,
                           str(s.date_range[1])[:10] if s.date_range[1] else None],
            "top_models": s.top_models.to_dict(orient="records"),
            "trend": trend.to_dict(orient="records"),
        }

    if name == "compare_countries":
        countries = inputs["countries"]
        g = summarize_all(
            df,
            start=_ts(inputs.get("start_date")),
            end=_ts(inputs.get("end_date")),
            countries=countries,
        )
        total = g.total_sales or 1
        rows = g.by_country[["country", "display_name", "sales", "quantity"]].copy()
        rows["share_pct"] = (rows["sales"] / total * 100).round(1)
        rows["sales"] = rows["sales"].round(0).astype(int)
        return rows.to_dict(orient="records")

    if name == "get_top_models":
        top_n = int(inputs.get("top_n", 10))
        country = inputs.get("country")
        sub = df
        if country:
            country_map = {c.lower(): c for c in df["country"].unique()}
            country = country_map.get(country.lower(), country)
            sub = df[df["country"] == country]
        models = (
            sub.groupby("model", as_index=False)
            .agg(sales=("sales", "sum"), quantity=("quantity", "sum"))
            .sort_values("sales", ascending=False)
            .head(top_n)
            .reset_index(drop=True)
        )
        models["sales"] = models["sales"].round(0).astype(int)
        return models.to_dict(orient="records")

    if name == "get_trend":
        gran = inputs["granularity"]
        country = inputs.get("country")
        if country:
            country_map = {c.lower(): c for c in df["country"].unique()}
            country = country_map.get(country.lower(), country)
            s = summarize_country(df, country, granularity=gran)
            trend = s.trend
        else:
            g = summarize_all(df, granularity=gran)
            trend = g.trend
        out = trend[["period_label", "sales", "quantity", "pop_pct", "yoy_pct"]].copy()
        out["sales"] = out["sales"].round(0).astype(int)
        out["pop_pct"] = out["pop_pct"].round(1)
        out["yoy_pct"] = out["yoy_pct"].round(1)
        return out.to_dict(orient="records")

    return {"error": f"Unknown tool: {name}"}


# ── 主入口 ─────────────────────────────────────────────────────────────────

def answer(question: str, session) -> str:
    """Run the tool-use loop and return a plain-text answer.

    Args:
        question: User's natural-language question (English or Chinese).
        session: SQLAlchemy Session — used to load the data once.

    Returns:
        A plain-text / markdown answer string.

    Raises:
        RuntimeError: If ANTHROPIC_API_KEY is not set.
        ImportError: If the anthropic package is not installed.
    """
    import anthropic  # 延迟导入，仅在实际调用时强依赖

    api_key = os.getenv("ANTHROPIC_API_KEY")
    if not api_key:
        raise RuntimeError(
            "ANTHROPIC_API_KEY is not set. Add it to your .env file."
        )

    df = load_sales_df(session)

    # 给模型一份轻量的数据概览，帮助它理解数据集边界（避免幻觉）
    countries_list = sorted(df["country"].unique().tolist()) if not df.empty else []
    context = (
        f"You are a data analyst assistant for a car-sales dashboard. "
        f"The dataset covers {len(df):,} sales records across "
        f"{df['country'].nunique() if not df.empty else 0} countries "
        f"from {str(df['date'].min())[:10] if not df.empty else 'N/A'} "
        f"to {str(df['date'].max())[:10] if not df.empty else 'N/A'}. "
        f"Available countries: {', '.join(countries_list)}. "
        "Use the provided tools to retrieve data before answering. "
        "Keep answers concise and data-driven."
    )

    client = anthropic.Anthropic(api_key=api_key)
    model = os.getenv("CHAT_MODEL", _DEFAULT_MODEL)
    messages = [{"role": "user", "content": question}]

    # 最多 5 轮工具调用（防止意外死循环）
    for _ in range(5):
        response = client.messages.create(
            model=model,
            max_tokens=1024,
            system=context,
            tools=_TOOLS,
            messages=messages,
        )

        # 没有工具调用 → 直接取文本返回
        if response.stop_reason == "end_turn":
            return _extract_text(response)

        # 有工具调用 → 执行并回传结果
        if response.stop_reason == "tool_use":
            # 把模型回复（含工具调用块）追加到消息链
            messages.append({"role": "assistant", "content": response.content})

            # 执行每个工具调用并收集结果
            tool_results = []
            for block in response.content:
                if block.type == "tool_use":
                    result = _run_tool(block.name, block.input, df)
                    tool_results.append({
                        "type": "tool_result",
                        "tool_use_id": block.id,
                        "content": json.dumps(result, ensure_ascii=False, default=str),
                    })

            messages.append({"role": "user", "content": tool_results})
            continue

        # 其他 stop_reason（max_tokens 等）
        break

    return _extract_text(response)


def _extract_text(response) -> str:
    """从 Anthropic response 提取纯文本内容。"""
    parts = [b.text for b in response.content if hasattr(b, "text")]
    return "\n".join(parts).strip() or "(no response)"
